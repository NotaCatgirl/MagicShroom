-- Application-owned tables only. Supabase Auth owns auth.users.
drop table if exists public.deck_cards;
drop table if exists public.decks;
drop table if exists public.cards;
drop table if exists public.users;

create table app_users (
    id bigint generated by default as identity primary key,
    auth_user_id uuid not null unique references auth.users(id) on delete cascade,
    email text not null,
    display_name text not null,
    role text not null default 'USER' check (role in ('USER', 'ADMIN'))
);

create table cards (
    id bigint generated by default as identity primary key,
    uuid uuid not null unique,
    card_name text not null,
    color_identity text[] not null default '{}',
    colors text[] not null default '{}',
    converted_mana_cost double precision,
    mana_cost text,
    scryfall_oracle_id uuid,
    card_text text,
    types text[] not null default '{}',
    subtypes text[] not null default '{}',
    supertypes text[] not null default '{}',
    printings text[] not null default '{}',
    foreign_data jsonb not null default '[]',
    legalities jsonb not null default '[]',
    purchase_urls jsonb not null default '[]',
    rulings jsonb not null default '[]'
    ,color_indicator text[] not null default '{}'
    ,edhrec_rank integer
    ,face_converted_mana_cost double precision
    ,hand text
    ,has_no_deck_limit boolean
    ,is_reserved boolean
    ,layout text
    ,leadership_skills jsonb
    ,life text
    ,loyalty text
    ,mtg_arena_id integer
    ,mtgo_foil_id integer
    ,mtgo_id integer
    ,names text[] not null default '{}'
    ,power text
    ,side text
    ,toughness text
    ,card_type text
);
create index cards_name_search_idx on cards (lower(card_name) text_pattern_ops);
create index cards_color_identity_idx on cards using gin (color_identity);

create table decks (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_users(id) on delete cascade,
    name varchar(100) not null
);
create index decks_user_id_idx on decks (user_id);

create table deck_cards (
    deck_id bigint not null references decks(id) on delete cascade,
    card_id bigint not null references cards(id) on delete restrict,
    quantity integer not null check (quantity > 0),
    section text not null check (section in ('MAINBOARD', 'SIDEBOARD', 'COMMANDER', 'MAYBEBOARD')),
    primary key (deck_id, card_id)
);
create index deck_cards_card_id_idx on deck_cards (card_id);

-- Database credentials must be server-side. Access to app_users/decks is mediated by the API.
alter table app_users enable row level security;
alter table cards enable row level security;
alter table decks enable row level security;
alter table deck_cards enable row level security;
revoke all on app_users, cards, decks, deck_cards from anon, authenticated;
revoke all on sequence app_users_id_seq, cards_id_seq, decks_id_seq from anon, authenticated;
